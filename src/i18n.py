class I18n:
    """Pequeño helper de traducciones con idioma activo mutable."""

    def __init__(self, language: str = "Español"):
        self.language = language if language in STRINGS else "Español"

    def set_language(self, language: str) -> None:
        if language in STRINGS:
            self.language = language

    def t(self, key: str) -> str:
        return STRINGS.get(self.language, STRINGS["Español"]).get(key, key)
